export const bySlug = (slug) => products.find((x) => x.slug === slug);
export const inCat = (cat) => products.filter((x) => x.cat === cat);
export const featured = (n = 6) => products.filter((x) => x.featured).slice(0, n);
export const subLabel = (cat, sub) => {
  const found = categories[cat]?.subs.find(([id]) => id === sub);
  return found ? found[1] : { en: sub, hi: sub };
};

export const priceBands = [
  { id: 'u10', max: 10000, label: { en: 'Under ₹10,000', hi: '₹10,000 से कम' } },
  { id: '10-20', min: 10000, max: 20000, label: { en: '₹10,000 – ₹20,000', hi: '₹10,000 – ₹20,000' } },
  { id: '20-40', min: 20000, max: 40000, label: { en: '₹20,000 – ₹40,000', hi: '₹20,000 – ₹40,000' } },
  { id: 'o40', min: 40000, label: { en: 'Above ₹40,000', hi: '₹40,000 से ऊपर' } },
];

export function bandOf(product) {
  if (product.price == null) return null;
  const b = priceBands.find(
    (b) => (b.min == null || product.price >= b.min) && (b.max == null || product.price < b.max)
  );
  return b ? b.id : null;
}
